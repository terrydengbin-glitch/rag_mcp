def read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(payload, dict):
        raise ValueError(f"{path} must contain a JSON object.")
    return payload


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def append_unique_strings(existing: Any, additions: list[str]) -> list[str]:
    values = [str(item) for item in existing if isinstance(item, str)] if isinstance(existing, list) else []
    for addition in additions:
        if addition not in values:
            values.append(addition)
    return values


def append_source_once(item: dict[str, Any], source: dict[str, Any]) -> None:
    refs = item.setdefault("source_refs", [])
    if any(isinstance(src, dict) and src.get("source_url") == source["source_url"] for src in refs):
        return
    existing_ids = {src.get("source_id") for src in refs if isinstance(src, dict)}
    payload = dict(source)
    if payload["source_id"] in existing_ids:
        max_id = 0
        for src in refs:
            if not isinstance(src, dict):
                continue
            match = re.search(r"(\d+)$", str(src.get("source_id", "")))
            if match:
                max_id = max(max_id, int(match.group(1)))
        payload["source_id"] = f"src_{max_id + 1:03d}"
    refs.append(payload)


