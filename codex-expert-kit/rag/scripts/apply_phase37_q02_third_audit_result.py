def validate(item: dict[str, Any]) -> list[dict[str, str]]:
    failures: list[dict[str, str]] = []
    if item.get("status", {}).get("ingestion_decision") != "accepted_for_draft":
        failures.append({"failure": "candidate_not_accepted_for_draft"})
    if item.get("classification", {}).get("canonical_node_id") != "kt.quant_foundation.risk_normalized_metrics":
        failures.append({"failure": "canonical_node_not_risk_normalized_metrics"})
    if item.get("workflow", {}).get("default_guidance_allowed") is not False:
        failures.append({"failure": "default_guidance_allowed_not_false"})
    if item.get("workflow", {}).get("approved_allowed") is not False:
        failures.append({"failure": "approved_allowed_not_false"})
    if item.get("workflow", {}).get("hard_gate_allowed") is not False:
        failures.append({"failure": "hard_gate_allowed_not_false"})
    limitations = json.dumps(item.get("source_quality", {}).get("limitations", []), ensure_ascii=False)
    if "主归属仍为 kt.quant_foundation.position_sizing" in limitations or "保留主归属 kt.quant_foundation.position_sizing" in limitations:
        failures.append({"failure": "stale_position_sizing_limitation_remains"})
    if int(item.get("source_quality", {}).get("primary_source_count", 99)) > 1:
        failures.append({"failure": "primary_source_count_still_overstated"})
    if has_mojibake(item):
        failures.append({"failure": "mojibake_marker_detected"})
    return failures


